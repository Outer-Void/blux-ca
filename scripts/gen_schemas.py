#!/usr/bin/env python3
"""Generate cA 2 JSON Schemas (src/blux_ca/construction/schemas/) and .blux/capabilities.yaml from spec.py.

python scripts/gen_schemas.py          # write
python scripts/gen_schemas.py --check  # exit 1 if the committed files differ (CI)
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from blux_ca.construction import spec  # noqa: E402
from blux_ca.construction.api import CAPABILITIES  # noqa: E402
from blux_ca.construction.common import ENGINE_VERSION  # noqa: E402

OUT = ROOT / "src" / "blux_ca" / "construction" / "schemas"
D = "https://json-schema.org/draft/2020-12/schema"
READ_ONLY = {"artifact.validate"}
IDEMPOTENT = {"artifact.construct", "artifact.validate", "config.generate"}


def with_header(schema: dict[str, Any], schema_id: str, title: str) -> dict[str, Any]:
    return {"$schema": D, "$id": f"urn:outervoid:ca:{schema_id}", "title": title, **schema}


def files() -> dict[Path, str]:
    out: dict[Path, str] = {}

    def put(name: str, doc: dict[str, Any]) -> None:
        out[OUT / name] = json.dumps(doc, indent=2, sort_keys=True) + "\n"

    for cap in CAPABILITIES:
        put(
            f"{cap}.request.v1.json",
            with_header(
                {**spec.REQUESTS[cap], "description": spec.SUMMARIES[cap]}, f"{cap}:request:v1", f"{cap} request"
            ),
        )
    put("result.v1.json", with_header(spec.RESULT, "result:v1", "ca.result v1"))
    put("check.v1.json", with_header(spec.CHECK, "check:v1", "ca.check v1"))
    put("changeset.v1.json", with_header(spec.CHANGESET, "changeset:v1", "ca.changeset v1"))

    lines = [
        "# GENERATED by scripts/gen_schemas.py; do not edit. cA construction and repair capabilities (docs/BLUX.md).",
        "# Writing capabilities change files in the given workspace only, through a changeset with rollback",
        "# artifacts. None of them certifies its result: DAT validates (certified is always false).",
        "contract: blux.capability-set",
        'contract_version: "1.0"',
        "capabilities:",
    ]
    for cap in CAPABILITIES:
        compact = json.dumps
        request = with_header(
            {**spec.REQUESTS[cap], "description": spec.SUMMARIES[cap]}, f"{cap}:request:v1", f"{cap} request"
        )
        result = with_header(
            spec.output_schema(cap),
            "check:v1" if cap in READ_ONLY else "result:v1",
            "ca.check v1" if cap in READ_ONLY else "ca.result v1",
        )
        perms = ["fs:read:workspace"] + ([] if cap in READ_ONLY else ["fs:write:workspace"])
        lines += [
            "  - contract: blux.capability",
            '    contract_version: "1.0"',
            f"    capability_id: {cap}",
            f"    version: {ENGINE_VERSION}",
            f"    summary: {json.dumps(spec.SUMMARIES[cap])}",
            '    contract_versions: ["1.0"]',
            f"    input_schema: {compact(request, sort_keys=True, separators=(',', ':'))}",
            f"    output_schema: {compact(result, sort_keys=True, separators=(',', ':'))}",
            f"    side_effects: {'read' if cap in READ_ONLY else 'write'}",
            f"    required_permissions: {json.dumps(perms)}",
            f"    idempotent: {'true' if cap in IDEMPOTENT else 'false'}",
            "    timeout_ms: 120000",
            "    provider:",
            "      repository: Outer-Void/blux-ca",
            "      kind: subprocess",
            f"      entrypoint: ca blux-capability {cap}",
            "    labels:",
            "      authority: construction",
            '      certifies: "false"',
            "      engine: ca-2",
        ]
    out[ROOT / ".blux" / "capabilities.yaml"] = "\n".join(lines) + "\n"
    return out


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for path, text in files().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path.relative_to(ROOT))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    if check and stale:
        print("stale generated files (run scripts/gen_schemas.py):", *stale, sep="\n  ")
        return 1
    print("up to date" if not stale else f"wrote {len(stale)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
